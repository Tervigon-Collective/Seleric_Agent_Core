#!/usr/bin/env python3
"""SEM-00 semantic surface inventory — build, write and gate.

Builds the machine-readable physical-view / metric / ownership / conflict /
lineage / consumer-dependency inventories from the live ClickHouse ``serve``
schema, the Cube v2 model and the versioned catalogue, and (optionally) the
Seleric Agent registry. Output is deterministic (SEM00-T06).

  uv run python scripts/build_semantic_inventory.py --write
      gather live, write doc/semantic_inventory/*.json + manifest.json
  uv run python scripts/build_semantic_inventory.py --check
      rebuild and fail (exit 1) if the artifacts are stale or a gate conflict exists
  uv run python scripts/build_semantic_inventory.py --snapshot out.json
      capture a replayable snapshot (for offline tests)
  uv run python scripts/build_semantic_inventory.py --from-snapshot out.json --write
      rebuild artifacts without touching ClickHouse / Cube

Gate: exits non-zero when any conflict of severity ``error`` is present
(unclassified view, unmapped Cube member, missing metric binding, duplicate id,
unknown Agent metric). Warnings and info are reported but do not fail the gate.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from seleric_mcp.semantic_inventory import build_inventory, content_hash  # noqa: E402
from seleric_mcp.semantic_inventory.sources import (  # noqa: E402
    load_snapshot,
    save_snapshot,
    snapshot_from_live,
)

OUT_DIR = ROOT / "doc" / "semantic_inventory"
MANIFEST = OUT_DIR / "manifest.json"


def _write(inv) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    d = inv.to_dict()
    (OUT_DIR / "inventory.json").write_text(json.dumps(d, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "physical_views.json").write_text(json.dumps(d["physical_views"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "metric_inventory.json").write_text(json.dumps(d["metrics"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "semantic_ownership.json").write_text(json.dumps(d["ownership"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "conflicts.json").write_text(json.dumps(d["conflicts"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "lineage.json").write_text(json.dumps(d["lineage"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "consumer_dependencies.json").write_text(json.dumps(d["consumer_dependencies"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (OUT_DIR / "INVENTORY.md").write_text(_markdown(inv), encoding="utf-8")
    MANIFEST.write_text(
        json.dumps(
            {
                "catalogue_version": inv.catalogue_version,
                "content_hash": content_hash(inv),
                "counts": {
                    "physical_views": len(inv.physical_views),
                    "metrics": len(inv.metrics),
                    "conflicts": len(inv.conflicts),
                    "cube_members": inv.cube.get("members", 0),
                },
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )


def _markdown(inv) -> str:
    roles = Counter(v.role for v in inv.physical_views)
    kinds = Counter(c["kind"] for c in inv.conflicts)
    lines = [
        "# SEM-00 — Semantic Surface Inventory",
        "",
        "> Generated by `scripts/build_semantic_inventory.py`. Do not hand-edit.",
        "",
        f"- Catalogue version: `{inv.catalogue_version}`",
        f"- Content hash: `{content_hash(inv)}`",
        f"- Physical serving views classified: **{len(inv.physical_views)}**",
        f"- Catalogue metrics inventoried: **{len(inv.metrics)}**",
        f"- Cube v2 members: **{inv.cube.get('members', 0)}** across {len(inv.cube.get('views', []))} views",
        "",
        "## Views by declared role",
        "",
        "| role | count |",
        "|---|---|",
    ]
    lines += [f"| {r} | {n} |" for r, n in sorted(roles.items())]
    lines += ["", "## Conflicts / drift (flagged, not auto-resolved)", "", "| kind | count |", "|---|---|"]
    lines += [f"| {k} | {n} |" for k, n in sorted(kinds.items())] or ["| (none) | 0 |"]
    errs = [c for c in inv.conflicts if c.get("severity") == "error"]
    lines += ["", f"Gate: **{'FAIL' if errs else 'PASS'}** ({len(errs)} error conflict(s)).", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="write artifacts to doc/semantic_inventory")
    ap.add_argument("--check", action="store_true", help="fail if artifacts are stale or an error gate is present")
    ap.add_argument("--snapshot", metavar="FILE", help="capture a replayable snapshot and write nothing else")
    ap.add_argument("--from-snapshot", metavar="FILE", help="build from a captured snapshot instead of live")
    ap.add_argument("--agent", metavar="DIR", help="path to the Seleric_Agent checkout for the registry surface")
    ap.add_argument("--json", action="store_true", help="print the full inventory as JSON to stdout")
    args = ap.parse_args(argv)

    if args.from_snapshot:
        snapshot = load_snapshot(Path(args.from_snapshot))
    else:
        snapshot = snapshot_from_live(agent_dir=Path(args.agent) if args.agent else None)

    if args.snapshot:
        save_snapshot(snapshot, Path(args.snapshot))

    inv = build_inventory(snapshot)
    errs = [c for c in inv.conflicts if c.get("severity") == "error"]

    if args.json:
        json.dump(inv.to_dict(), sys.stdout, indent=2, sort_keys=True)
        sys.stdout.write("\n")

    if args.write:
        _write(inv)
        print(f"wrote {OUT_DIR} (hash {content_hash(inv)})")

    if args.check:
        if not MANIFEST.is_file():
            print("FAIL: no manifest — run --write first", file=sys.stderr)
            return 1
        committed = json.loads(MANIFEST.read_text(encoding="utf-8"))
        fresh = content_hash(inv)
        if committed.get("content_hash") != fresh:
            print(f"FAIL: inventory stale (committed {committed.get('content_hash')} != live {fresh})", file=sys.stderr)
            return 1
        if errs:
            print(f"FAIL: {len(errs)} error conflict(s): {[c['kind'] for c in errs]}", file=sys.stderr)
            return 1
        print(f"OK: inventory deterministic and gate-clean ({fresh})")
        return 0

    if not (args.write or args.json or args.snapshot):
        print(f"views={len(inv.physical_views)} metrics={len(inv.metrics)} conflicts={len(inv.conflicts)} "
              f"errors={len(errs)} hash={content_hash(inv)}")
    return 1 if errs and not args.write else 0


if __name__ == "__main__":
    raise SystemExit(main())
